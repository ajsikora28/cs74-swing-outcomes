from features import PITCH_FEATURES, PITCH_CATEGORICAL_FEATURES, CONTEXT_FEATURES, CONTEXT_CATEGORICAL_FEATURES
from evaluate import evaluate_model
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import log_loss
import matplotlib.pyplot as plt
import pandas as pd

train_x = pd.read_csv("data/processed/train_x.csv")
train_x_pitch = train_x[PITCH_FEATURES].copy()
train_x_context = train_x[CONTEXT_FEATURES].copy()
train_y = pd.read_csv("data/processed/train_y.csv")["swing_result"]
validation_x = pd.read_csv("data/processed/validation_x.csv")
validation_x_pitch = validation_x[PITCH_FEATURES].copy()
validation_x_context = validation_x[CONTEXT_FEATURES].copy()
validation_y = pd.read_csv("data/processed/validation_y.csv")["swing_result"]

# One-hot encode categorical features
# Claude Opus 5.5 assisted in writing the code for this function
def encode(train, val, categorical):
    train_encoded = pd.get_dummies(train, columns=categorical, dtype=float)
    val_encoded = pd.get_dummies(val, columns=categorical, dtype=float)
    val_encoded = val_encoded.reindex(columns=train_encoded.columns, fill_value=0)
    return train_encoded, val_encoded

train_pitch_encoded, val_pitch_encoded = encode(train_x_pitch, validation_x_pitch, PITCH_CATEGORICAL_FEATURES)
train_context_encoded, val_context_encoded = encode(train_x_context, validation_x_context, CONTEXT_CATEGORICAL_FEATURES)

# Set to True to run the tuning process
RUN_TUNING = False

if not RUN_TUNING:
    results = pd.read_csv("results/metrics/rf_tuning_results.csv")

else:
    results = []
    for d in [12, 18, 24, 30, 36, 42]:
        for leaf in [2, 5, 10, 50, 200]:
            rf_pitch = RandomForestClassifier(n_estimators=100, max_depth=d, min_samples_leaf=leaf, max_samples=0.7, random_state=42, n_jobs=-1).fit(train_pitch_encoded, train_y)
            rf_context = RandomForestClassifier(n_estimators=100, max_depth=d, min_samples_leaf=leaf, max_samples=0.7, random_state=42, n_jobs=-1).fit(train_context_encoded, train_y)

            pitch_loss = log_loss(validation_y, rf_pitch.predict_proba(val_pitch_encoded), labels=rf_pitch.classes_)
            context_loss = log_loss(validation_y, rf_context.predict_proba(val_context_encoded), labels=rf_context.classes_)

            results.append({"max_depth": d, "min_samples_leaf": leaf, "best_pitch_loss": pitch_loss, "best_context_loss": context_loss})
            pd.DataFrame(results).to_csv("results/metrics/rf_tuning_results.csv", index=False)
            print(f"depth={d}, leaf={leaf}: pitch {pitch_loss:.4f} | context {context_loss:.4f}", flush=True)

    results = pd.DataFrame(results)
    print("\n", results.to_string(index=False))


# Heatmap of validation log loss for each max_depth / min_samples_leaf combination
# Adapted from the HGB heatmap code (originally generated by Claude Opus 5.5)
tuning = pd.read_csv("results/metrics/rf_tuning_results.csv")
fig, axes = plt.subplots(1, 2, figsize=(10, 4.5))

for ax, model in zip(axes, ["pitch", "context"]):
    losses = tuning.pivot(index="max_depth", columns="min_samples_leaf", values=f"best_{model}_loss")

    im = ax.imshow(losses, cmap="viridis_r", aspect="auto")
    ax.set_xticks(range(len(losses.columns)), losses.columns)
    ax.set_yticks(range(len(losses.index)), losses.index)

    midpoint = losses.values.mean()
    for i in range(losses.shape[0]):
        for j in range(losses.shape[1]):
            value = losses.iloc[i, j]
            ax.text(j, i, f"{value:.4f}", ha="center", va="center", fontsize=9,
                    color="white" if value > midpoint else "black")

    ax.set_title(f"{model.capitalize()} model: validation log loss")
    ax.set_xlabel("Minimum samples per leaf")
    ax.set_ylabel("Max depth")
    fig.colorbar(im, ax=ax)

fig.tight_layout()
fig.savefig("results/figures/rf_tuning_heatmap.png", dpi=200)


best_pitch_row = results[results["best_pitch_loss"] == results["best_pitch_loss"].min()].iloc[0]
best_context_row = results[results["best_context_loss"] == results["best_context_loss"].min()].iloc[0]

pitch_max_depth = int(best_pitch_row["max_depth"])
context_max_depth = int(best_context_row["max_depth"])
pitch_leaf = int(best_pitch_row["min_samples_leaf"])
context_leaf = int(best_context_row["min_samples_leaf"])

# Quick check of n_estimators: compare 100 and 300 trees at the best depth and leaf size
# The basis for this code was written by us but was simplified and edited by Claude Opus 5.5
rf_pitch_100 = RandomForestClassifier(n_estimators=100, max_depth=pitch_max_depth, min_samples_leaf=pitch_leaf, max_samples=0.7, random_state=42, n_jobs=-1).fit(train_pitch_encoded, train_y)
rf_pitch_300 = RandomForestClassifier(n_estimators=300, max_depth=pitch_max_depth, min_samples_leaf=pitch_leaf, max_samples=0.7, random_state=42, n_jobs=-1).fit(train_pitch_encoded, train_y)
rf_context_100 = RandomForestClassifier(n_estimators=100, max_depth=context_max_depth, min_samples_leaf=context_leaf, max_samples=0.7, random_state=42, n_jobs=-1).fit(train_context_encoded, train_y)
rf_context_300 = RandomForestClassifier(n_estimators=300, max_depth=context_max_depth, min_samples_leaf=context_leaf, max_samples=0.7, random_state=42, n_jobs=-1).fit(train_context_encoded, train_y)

pitch_loss_100 = log_loss(validation_y, rf_pitch_100.predict_proba(val_pitch_encoded), labels=rf_pitch_100.classes_)
pitch_loss_300 = log_loss(validation_y, rf_pitch_300.predict_proba(val_pitch_encoded), labels=rf_pitch_300.classes_)
context_loss_100 = log_loss(validation_y, rf_context_100.predict_proba(val_context_encoded), labels=rf_context_100.classes_)
context_loss_300 = log_loss(validation_y, rf_context_300.predict_proba(val_context_encoded), labels=rf_context_300.classes_)

print(f"Pitch: 100 trees {pitch_loss_100:.4f} | 300 trees {pitch_loss_300:.4f}", flush=True)
print(f"Context: 100 trees {context_loss_100:.4f} | 300 trees {context_loss_300:.4f}", flush=True)

pd.DataFrame([
    {"features": "pitch", "n_estimators": 100, "log_loss": pitch_loss_100},
    {"features": "pitch", "n_estimators": 300, "log_loss": pitch_loss_300},
    {"features": "context", "n_estimators": 100, "log_loss": context_loss_100},
    {"features": "context", "n_estimators": 300, "log_loss": context_loss_300},
]).to_csv("results/metrics/rf_n_estimators.csv", index=False)

# Lower log loss is better; a tie goes to the simpler 100-tree model
if pitch_loss_100 <= pitch_loss_300:
    best_pitch_n, best_pitch_model = 100, rf_pitch_100
else:
    best_pitch_n, best_pitch_model = 300, rf_pitch_300

if context_loss_100 <= context_loss_300:
    best_context_n, best_context_model = 100, rf_context_100
else:
    best_context_n, best_context_model = 300, rf_context_300

pitch_probs = pd.DataFrame(best_pitch_model.predict_proba(val_pitch_encoded), columns=best_pitch_model.classes_, index=val_pitch_encoded.index)
context_probs = pd.DataFrame(best_context_model.predict_proba(val_context_encoded), columns=best_context_model.classes_, index=val_context_encoded.index)

log_loss_pitch, brier_pitch, accuracy_pitch = evaluate_model(validation_y, pitch_probs)
log_loss_context, brier_context, accuracy_context = evaluate_model(validation_y, context_probs)

print("Log Loss (Pitch):", log_loss_pitch)
print("Brier Score (Pitch):", brier_pitch)
print("Accuracy (Pitch):", accuracy_pitch)
print("Log Loss (Context):", log_loss_context)
print("Brier Score (Context):", brier_context)
print("Accuracy (Context):", accuracy_context)


final = pd.DataFrame([
    {"model": "rf", "features": "pitch", "max_depth": pitch_max_depth,
     "min_samples_leaf": pitch_leaf, "n_estimators": best_pitch_n, 
     "val_log_loss": log_loss_pitch, "val_brier": brier_pitch, "val_accuracy": accuracy_pitch},
    {"model": "rf", "features": "context", "max_depth": context_max_depth,
     "min_samples_leaf": context_leaf, "n_estimators": best_context_n,
     "val_log_loss": log_loss_context, "val_brier": brier_context, "val_accuracy": accuracy_context},
])

final.to_csv("results/metrics/rf_settings.csv", index=False)