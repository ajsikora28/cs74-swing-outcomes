## HistGradientBoostingClassifier
from evaluate import evaluate_model
from features import PITCH_CATEGORICAL_FEATURES, CONTEXT_CATEGORICAL_FEATURES, PITCH_FEATURES, CONTEXT_FEATURES
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import log_loss
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import time

train_x = pd.read_csv("data/processed/train_x.csv")
train_x_pitch = train_x[PITCH_FEATURES]
train_x_context = train_x[CONTEXT_FEATURES]
train_y = pd.read_csv("data/processed/train_y.csv")["swing_result"] # Select the column so it's a Series for HistGradientBoostingClassifier
validation_x = pd.read_csv("data/processed/validation_x.csv")
validation_x_pitch = validation_x[PITCH_FEATURES]
validation_x_context = validation_x[CONTEXT_FEATURES]
validation_y = pd.read_csv("data/processed/validation_y.csv")["swing_result"]

# Set to True to run the tuning process (will take several hours)
RUN_TUNING = False

if not RUN_TUNING:
    results = pd.read_csv("results/metrics/hgb_tuning_results.csv")

else:
    # Tune max_depth and learning_rate for each model
    results = []
    start_time = time.perf_counter()
    for d in range(3, 11):
        for r in [0.01, 0.05, 0.1, 0.2]:
            hgb_pitch = HistGradientBoostingClassifier(random_state=10, learning_rate=r, max_iter=1000, max_depth=d, max_leaf_nodes=None, early_stopping=False, categorical_features=PITCH_CATEGORICAL_FEATURES).fit(train_x_pitch, train_y)
            hgb_context = HistGradientBoostingClassifier(random_state=10, learning_rate=r, max_iter=1000, max_depth=d, max_leaf_nodes=None, early_stopping=False, categorical_features=CONTEXT_CATEGORICAL_FEATURES).fit(train_x_context, train_y)

            pitch_losses = []
            for probs in hgb_pitch.staged_predict_proba(validation_x_pitch):
                pitch_losses.append(log_loss(validation_y, probs, labels=hgb_pitch.classes_))

            context_losses = []
            for probs in hgb_context.staged_predict_proba(validation_x_context):
                context_losses.append(log_loss(validation_y, probs, labels=hgb_context.classes_))

            best_pitch_index = np.argmin(pitch_losses)
            best_pitch_loss = pitch_losses[best_pitch_index]
            best_context_index = np.argmin(context_losses)
            best_context_loss = context_losses[best_context_index]

            results.append({"max_depth": d, "learning_rate": r, "best_pitch_iters": best_pitch_index + 1, "best_pitch_loss": best_pitch_loss,
                                    "best_context_iters": best_context_index + 1, "best_context_loss": best_context_loss})
            
            pd.DataFrame(results).to_csv("results/metrics/hgb_tuning_results.csv", index=False)

            print(f"[{len(results)}/32] depth={d}, lr={r} | "
                f"pitch {best_pitch_loss:.4f} ({best_pitch_index + 1} trees) | "
                f"context {best_context_loss:.4f} ({best_context_index + 1} trees) | "
                f"{(time.perf_counter() - start_time) / 60:.0f} min elapsed", flush=True)

    results = pd.DataFrame(results)


    # Make a heatmap for each model showing best log loss for each combination of max_depth and learning_rate
    # The code for this heatmap was modified from code generated by Claude Opus 5.5
    fig, axes = plt.subplots(1,2,figsize=(12,5))

    for ax, model in zip(axes, ["pitch", "context"]):
        losses = results.pivot(index="max_depth", columns="learning_rate", values=f"best_{model}_loss")
        iters = results.pivot(index="max_depth", columns="learning_rate", values=f"best_{model}_iters")

        im = ax.imshow(losses, cmap="viridis_r", aspect="auto")
        ax.set_xticks(range(len(losses.columns)), losses.columns)
        ax.set_yticks(range(len(losses.index)), losses.index)

        midpoint = losses.values.mean()
        for i in range(losses.shape[0]):
            for j in range(losses.shape[1]):
                value = losses.iloc[i, j]
                ax.text(j, i, f"{value:.4f}\n({iters.iloc[i, j]} trees)", ha="center", va="center",
                        fontsize=8, color="white" if value > midpoint else "black")

        ax.set_title(f"{model.capitalize()} model: validation log loss")
        ax.set_xlabel("Learning rate")
        ax.set_ylabel("Max depth")
        fig.colorbar(im, ax=ax)

    fig.tight_layout()
    fig.savefig("results/figures/hgb_tuning_heatmap.png", dpi=200)



# Get the best hyperparameters and create final model
best_pitch_row = results[results["best_pitch_loss"] == results["best_pitch_loss"].min()].iloc[0]
best_context_row = results[results["best_context_loss"] == results["best_context_loss"].min()].iloc[0]

pitch_max_depth = int(best_pitch_row["max_depth"])
context_max_depth = int(best_context_row["max_depth"])
pitch_learning_rate = best_pitch_row["learning_rate"]
context_learning_rate = best_context_row["learning_rate"]
pitch_max_iter = int(best_pitch_row["best_pitch_iters"])
context_max_iter = int(best_context_row["best_context_iters"])

hgb_pitch = HistGradientBoostingClassifier(random_state=10, learning_rate=pitch_learning_rate, max_iter=pitch_max_iter, max_depth=pitch_max_depth, max_leaf_nodes=None, early_stopping=False, categorical_features=PITCH_CATEGORICAL_FEATURES).fit(train_x_pitch, train_y)
hgb_context = HistGradientBoostingClassifier(random_state=10, learning_rate=context_learning_rate, max_iter=context_max_iter, max_depth=context_max_depth, max_leaf_nodes=None, early_stopping=False, categorical_features=CONTEXT_CATEGORICAL_FEATURES).fit(train_x_context, train_y)

pitch_probs = pd.DataFrame(hgb_pitch.predict_proba(validation_x_pitch), columns = hgb_pitch.classes_, index = validation_x_pitch.index)
context_probs = pd.DataFrame(hgb_context.predict_proba(validation_x_context), columns = hgb_context.classes_, index = validation_x_context.index)

log_loss_pitch, brier_pitch, accuracy_pitch = evaluate_model(validation_y, pitch_probs)
log_loss_context, brier_context, accuracy_context = evaluate_model(validation_y, context_probs)

print("Log Loss (Pitch):", log_loss_pitch)
print("Brier Score (Pitch):", brier_pitch)
print("Accuracy (Pitch):", accuracy_pitch)
print("Log Loss (Context):", log_loss_context)
print("Brier Score (Context):", brier_context)
print("Accuracy (Context):", accuracy_context)


final = pd.DataFrame([
    {"model": "hgb", "features": "pitch", "max_depth": pitch_max_depth,
     "learning_rate": pitch_learning_rate, "max_iter": pitch_max_iter,
     "val_log_loss": log_loss_pitch, "val_brier": brier_pitch, "val_accuracy": accuracy_pitch},
    {"model": "hgb", "features": "context", "max_depth": context_max_depth,
     "learning_rate": context_learning_rate, "max_iter": context_max_iter,
     "val_log_loss": log_loss_context, "val_brier": brier_context, "val_accuracy": accuracy_context},
])

final.to_csv("results/metrics/hgb_settings.csv", index=False)