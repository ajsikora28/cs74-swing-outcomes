## LogisticRegression
from features import PITCH_FEATURES, PITCH_CATEGORICAL_FEATURES, CONTEXT_FEATURES, CONTEXT_CATEGORICAL_FEATURES
from evaluate import evaluate_model
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import log_loss
import pandas as pd
import matplotlib.pyplot as plt
import time

train_x = pd.read_csv("data/processed/train_x.csv")
train_x_pitch = train_x[PITCH_FEATURES].copy()
train_x_context = train_x[CONTEXT_FEATURES].copy()
train_y = pd.read_csv("data/processed/train_y.csv")["swing_result"]
validation_x = pd.read_csv("data/processed/validation_x.csv")
validation_x_pitch = validation_x[PITCH_FEATURES].copy()
validation_x_context = validation_x[CONTEXT_FEATURES].copy()
validation_y = pd.read_csv("data/processed/validation_y.csv")["swing_result"]


# Scale numeric features (fit on train only) and one-hot encode categorical features
# Claude Opus 5.5 assisted in writing the code for this function
def encode(train, val, categorical):
    numeric = [c for c in train.columns if c not in categorical]
    scaler = StandardScaler()
    train[numeric] = scaler.fit_transform(train[numeric])
    val[numeric] = scaler.transform(val[numeric])

    train_encoded = pd.get_dummies(train, columns=categorical, dtype=float)
    val_encoded = pd.get_dummies(val, columns=categorical, dtype=float)
    val_encoded = val_encoded.reindex(columns=train_encoded.columns, fill_value=0)
    return train_encoded, val_encoded

train_pitch_encoded, val_pitch_encoded = encode(train_x_pitch, validation_x_pitch, PITCH_CATEGORICAL_FEATURES)
train_context_encoded, val_context_encoded = encode(train_x_context, validation_x_context, CONTEXT_CATEGORICAL_FEATURES)


# Set to True to run the tuning process
RUN_TUNING = False

if not RUN_TUNING:
    results = pd.read_csv("results/metrics/logreg_tuning_results.csv")

else:
    # Tune penalty and C for each model
    results = []
    start_time = time.perf_counter()
    for penalty in [0, 1]:
        for c in [0.1, 1, 10]:
            solver = "saga" if penalty == 1 else "lbfgs"
            logreg_pitch = LogisticRegression(l1_ratio=penalty, C=c, solver=solver, max_iter=1000, random_state=42).fit(train_pitch_encoded, train_y)
            logreg_context = LogisticRegression(l1_ratio=penalty, C=c, solver=solver, max_iter=1000, random_state=42).fit(train_context_encoded, train_y)

            pitch_loss = log_loss(validation_y, logreg_pitch.predict_proba(val_pitch_encoded), labels=logreg_pitch.classes_)
            context_loss = log_loss(validation_y, logreg_context.predict_proba(val_context_encoded), labels=logreg_context.classes_)

            penalty_name = "L2" if penalty == 0 else "L1"
            results.append({"penalty": penalty_name, "C": c, "best_pitch_loss": pitch_loss, "best_context_loss": context_loss})
            pd.DataFrame(results).to_csv("results/metrics/logreg_tuning_results.csv", index=False)

            print(f"[{len(results)}/6] {penalty_name.upper()}, C={c} | pitch {pitch_loss:.4f} | context {context_loss:.4f} | "
                f"{(time.perf_counter() - start_time) / 60:.1f} min elapsed", flush=True)

    results = pd.DataFrame(results)  # needed: results is still a list here, and the lines below require a DataFrame
    print("\n", results.to_string(index=False))


# Line plot of validation log loss vs. C for each penalty
# The code for this plot was modified from code generated by Claude Opus 5.5
tuning = pd.read_csv("results/metrics/logreg_tuning_results.csv")
c_values = sorted(tuning["C"].unique())
fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))

for ax, model in zip(axes, ["pitch", "context"]):
    for penalty, marker, label_offset in [("L2", "o", 8), ("L1", "s", -14)]:
        sub = tuning[tuning["penalty"] == penalty].sort_values("C")
        ax.plot(sub["C"], sub[f"best_{model}_loss"], marker=marker, label=penalty)
        for x, y in zip(sub["C"], sub[f"best_{model}_loss"]):
            ax.annotate(f"{y:.4f}", (x, y), textcoords="offset points", xytext=(0, label_offset),
                        ha="center", fontsize=8)

    ax.set_xscale("log")
    ax.set_xticks(c_values, [f"{c:g}" for c in c_values])
    ax.minorticks_off()
    ax.ticklabel_format(axis="y", useOffset=False)  # show actual log loss values, not an offset
    ax.margins(y=0.25)  # room for the value labels
    ax.set_title(f"{model.capitalize()} model: validation log loss")
    ax.set_xlabel("C (inverse regularization strength, log scale)")
    ax.set_ylabel("Log loss")
    ax.legend(title="Penalty")

fig.tight_layout()
fig.savefig("results/figures/logreg_tuning_plot.png", dpi=200)



# Get the best hyperparameters and create final model
best_pitch_row = results[results["best_pitch_loss"] == results["best_pitch_loss"].min()].iloc[0]
best_context_row = results[results["best_context_loss"] == results["best_context_loss"].min()].iloc[0]

pitch_penalty = best_pitch_row["penalty"]
context_penalty = best_context_row["penalty"]
pitch_C = float(best_pitch_row["C"])
context_C = float(best_context_row["C"])
pitch_solver = "saga" if pitch_penalty == "L1" else "lbfgs"
context_solver = "saga" if context_penalty == "L1" else "lbfgs"

logreg_pitch = LogisticRegression(l1_ratio=1 if pitch_penalty == "L1" else 0, C=pitch_C, solver=pitch_solver, max_iter=1000, random_state=42).fit(train_pitch_encoded, train_y)
logreg_context = LogisticRegression(l1_ratio=1 if context_penalty == "L1" else 0, C=context_C, solver=context_solver, max_iter=1000, random_state=42).fit(train_context_encoded, train_y)

pitch_probs = pd.DataFrame(logreg_pitch.predict_proba(val_pitch_encoded), columns=logreg_pitch.classes_, index=val_pitch_encoded.index)
context_probs = pd.DataFrame(logreg_context.predict_proba(val_context_encoded), columns=logreg_context.classes_, index=val_context_encoded.index)

log_loss_pitch, brier_pitch, accuracy_pitch = evaluate_model(validation_y, pitch_probs)
log_loss_context, brier_context, accuracy_context = evaluate_model(validation_y, context_probs)

print("Log Loss (Pitch):", log_loss_pitch)
print("Brier Score (Pitch):", brier_pitch)
print("Accuracy (Pitch):", accuracy_pitch)
print("Log Loss (Context):", log_loss_context)
print("Brier Score (Context):", brier_context)
print("Accuracy (Context):", accuracy_context)

final = pd.DataFrame([
    {"model": "logreg", "features": "pitch", "penalty": pitch_penalty, "C": pitch_C,
     "val_log_loss": log_loss_pitch, "val_brier": brier_pitch, "val_accuracy": accuracy_pitch},
    {"model": "logreg", "features": "context", "penalty": context_penalty, "C": context_C,
     "val_log_loss": log_loss_context, "val_brier": brier_context, "val_accuracy": accuracy_context},
])

final.to_csv("results/metrics/logreg_settings.csv", index=False)